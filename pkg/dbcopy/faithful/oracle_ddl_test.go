// A script with a row that needs a block of its own: its lines are all the generator's, and the batches around it are whole.
func TestOracleScriptWithBigBlobRows(t *testing.T) {
	e := sqliteWith(t, `CREATE TABLE b (id INTEGER PRIMARY KEY, x BLOB, t TEXT)`, `INSERT INTO b VALUES (1, x'01', 'a'), (2, zeroblob(2500), 'b'), (3, x'02', 'c'), (4, zeroblob(2001), NULL)`)
	script, _ := exportOracle(t, e)
	checkOracleLines(t, script)
	if n := strings.Count(script, "\n/\n"); n != 4 {
		t.Errorf("the check, two rows and the marker: %d blocks", n)
	}
	for _, want := range []string{"INSERT INTO \"b\" (\"id\", \"x\", \"t\") VALUES\n(1,TO_BLOB(HEXTORAW('01')),'a');\nCOMMIT;\nDECLARE\n  b1 BLOB;\nBEGIN\n", "(2,EMPTY_BLOB(),'b')\n  RETURNING \"x\" INTO b1;", "(4,EMPTY_BLOB(),NULL)"} {
		if !strings.Contains(script, want) {
			t.Errorf("no %q in\n%.1500s", want, script[strings.Index(script, "INSERT INTO"):])
		}
	}
}

func TestOracleScriptFraming(t *testing.T) {
	script, _ := exportOracle(t, sqliteWith(t, `CREATE TABLE a (id INTEGER PRIMARY KEY, v TEXT)`, `INSERT INTO a VALUES (1, 'x'), (2, 'y')`, `CREATE TABLE "b'c" (id INTEGER PRIMARY KEY)`, `INSERT INTO "b'c" VALUES (1)`))
	checkOracleLines(t, script)
	for _, want := range []string{
		"-- DemoDB contract edition\n-- Dataset: fixture\n-- Generated by datatug v0.0.0-test (datatug db copy --to sqlscript:///<file>.sql?dialect=oracle) from a SQLite file with SHA-256 " + strings.Repeat("ab", 32),
		"-- Licence: MIT\n-- Attribution: Someone\n", "NLS_LANG=.AL32UTF8 sqlplus -L -S <user>/<password>@<service> @<file>.sql", "-- Tables (2): a, b'c\n",
		"\nSET DEFINE OFF\nSET ESCAPE OFF\nSET CMDSEP OFF\nSET SQLTERMINATOR ';'\nSET SQLPREFIX #\nSET ECHO OFF\nSET FEEDBACK OFF\nSET VERIFY OFF\nWHENEVER SQLERROR EXIT FAILURE ROLLBACK\nWHENEVER OSERROR EXIT FAILURE ROLLBACK\nALTER SESSION SET NLS_COMP = BINARY NLS_SORT = BINARY;\nDECLARE\n",
		"IF DBMS_DB_VERSION.VERSION < 23 THEN", "IF 'é€😀' <> TO_CHAR(UNISTR('\\00E9\\20AC\\D83D\\DE00')) THEN", "IF cs <> 'AL32UTF8' THEN",
		"\nCREATE TABLE \"_demodb_import\" (\"dataset\" VARCHAR2(4000 BYTE), \"edition\" VARCHAR2(4000 BYTE), \"source_sha256\" VARCHAR2(64 CHAR) NOT NULL, \"datatug_version\" VARCHAR2(4000 BYTE), \"tables_count\" NUMBER(10,0) NOT NULL, \"rows_count\" NUMBER(19,0) NOT NULL);\n\nCREATE TABLE \"a\"",
		"COMMIT;\nDECLARE\n  n NUMBER;\nBEGIN\n  SELECT COUNT(*) INTO n FROM \"a\";\n  IF n <> 2 THEN RAISE_APPLICATION_ERROR(-20000, 'the load is incomplete: table a does not hold 2 rows'); END IF;\n  SELECT COUNT(*) INTO n FROM \"b'c\";\n  IF n <> 1 THEN RAISE_APPLICATION_ERROR(-20000, 'the load is incomplete: table b''c does not hold 1 rows'); END IF;\n  SELECT COUNT(*) INTO n FROM user_constraints WHERE table_name IN ('a', 'b''c') AND constraint_type IN ('P','U','R') AND status = 'ENABLED' AND validated = 'VALIDATED';\n  IF n <> 2 THEN RAISE_APPLICATION_ERROR(-20000, 'the load is incomplete: '||n||' keys in the catalog, not the 2 of the tables a to b''c'); END IF;\n  SELECT COUNT(*) INTO n FROM user_constraints WHERE table_name IN ('a', 'b''c') AND constraint_type = 'C' AND status = 'ENABLED' AND validated = 'VALIDATED';\n  IF n <> 2 THEN RAISE_APPLICATION_ERROR(-20000, 'the load is incomplete: '||n||' checks in the catalog, not the 2 of the tables a to b''c'); END IF;\n  SELECT COUNT(*) INTO n FROM user_indexes WHERE table_name IN ('a', 'b''c') AND index_type <> 'LOB';\n  IF n <> 2 THEN RAISE_APPLICATION_ERROR(-20000, 'the load is incomplete: '||n||' indexes in the catalog, not the 2 of the tables a to b''c'); END IF;\n",
		"  INSERT INTO \"_demodb_import\" VALUES\n('fixture','DemoDB contract edition','" + strings.Repeat("ab", 32) + "','v0.0.0-test',2,3);\n  COMMIT;\nEND;\n/\n-- end of script\n",
	} {
		if !strings.Contains(script, want) {
			t.Errorf("no %q in\n%s", want, script)
		}
	}
	// The marker is written in the block that counts the tables, after the counts: a wrong count raises before the insert.
	block := script[strings.LastIndex(script, "DECLARE\n  n NUMBER;"):]
	if strings.Index(block, "RAISE_APPLICATION_ERROR") > strings.Index(block, `INSERT INTO "_demodb_import"`) {
		t.Error("the counts come first")
	}
	// The script starts with the label of the edition and has no byte order mark; it is the same at every line end.
	if !strings.HasPrefix(script, "-- DemoDB contract edition\n") || strings.Contains(script, "\r") {
		t.Error("the start of the script")
	}
}

func TestOracleHeaderAndMarkerTexts(t *testing.T) {
	d := oracleDialect{}
	p := planOracle(t, `CREATE TABLE a (id INTEGER PRIMARY KEY)`)
	// An empty name and edition: the header says "database" and the marker holds NULL.
	h := Header{SourceSHA256: strings.Repeat("0", 64), Version: "v"}
	head := strings.Join(d.Header(p, h), "\n")
	if !strings.Contains(head, "-- Dataset: database\n") || strings.Contains(head, "Licence:") || strings.Contains(head, "Attribution:") {
		t.Errorf("%s", head)
	}
	epi := strings.Join(d.Epilogue(p, h), "\n")
	if !strings.Contains(epi, "VALUES\n(NULL,NULL,'"+strings.Repeat("0", 64)+"','v',1,0);") {
		t.Errorf("%s", epi)
	}
	h.Version = ""
	if epi := strings.Join(d.Epilogue(p, h), "\n"); !strings.Contains(epi, "',NULL,1,0);") {
		t.Errorf("%s", epi)
	}
	// An & in the header is followed by a space, whatever the client does with variables; no control character survives.
	h = Header{Name: "AT&T\r\nfoo", Edition: "a&&b", License: "x&y", Attribution: "p&q", SourceSHA256: "s", Version: "v"}
	head = strings.Join(d.Header(p, h), "\n")
	for _, want := range []string{"-- a& & b\n", "-- Dataset: AT& T foo\n", "-- Licence: x& y\n", "-- Attribution: p& q\n"} {
		if !strings.Contains(head, want) {
			t.Errorf("no %q in\n%s", want, head)
		}
	}
	// Warnings are listed in the header.
	p.Warnings = append(p.Warnings, Warning{Kind: "k", Object: "o", Message: "m & n"})
	if head := strings.Join(d.Header(p, h), "\n"); !strings.Contains(head, "-- 1 thing(s) are not carried exactly:\n-- [k] o: m &  n") {
		t.Errorf("%s", head)
	}
}

func TestOracleValidateHeader(t *testing.T) {
	d := oracleDialect{}
	if err := d.ValidateHeader(Header{Name: "ok", Edition: "é"}); err != nil {
		t.Error(err)
	}
	for _, h := range []Header{{Name: "a\xffb"}, {Edition: "a\xffb"}, {Name: "a\x00b"}, {Edition: "a\x00b"}, {Name: strings.Repeat("x", 4001)}, {Edition: strings.Repeat("é", 2001)}} {
		if err := d.ValidateHeader(h); err == nil {
			t.Errorf("%+v", h)
		}
	}
	_, err := ExportScript(context.Background(), ScriptRequest{Dialect: "oracle", DB: newSQLite(t).DB, Header: Header{Name: "a\x00b"}}, &bytes.Buffer{})
	var ue *ScriptUsageError
	if !errors.As(err, &ue) {
		t.Errorf("a header the script cannot carry is a usage error: %v", err)
	}
}

func TestJoinRowBreaksLongRows(t *testing.T) {
	if got := joinRow([]string{"a", "b", "c"}, 0); got != "(a,b,c)" {
		t.Errorf("%q", got)
	}
	// A value that would pass the limit starts a line; a literal with lines of its own sets where the line stands.
	if got := joinRow([]string{"aaaa", "bbbb", "cccc"}, 8); got != "(aaaa,\nbbbb,\ncccc)" {
		t.Errorf("%q", got)
	}
	if got := joinRow([]string{"x\nyy", "zz", "wwwwwwww"}, 8); got != "(x\nyy,zz,\nwwwwwwww)" {
		t.Errorf("%q", got)
	}
	if got := joinRow([]string{"aaaaaaaaaaaa", "b"}, 4); got != "(aaaaaaaaaaaa,\nb)" {
		t.Errorf("the first value is never moved: %q", got)
	}
}

// A dialect that has a RowStatement whose statement is an error, or that writes no row at all.
type errRowDialect struct{ oracleDialect }

func (errRowDialect) RowStatement(*ScriptTable, []any) (string, bool, error) {
	return "", false, errors.New("this row cannot be written")
}

