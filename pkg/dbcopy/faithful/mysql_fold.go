// foldName is a name as MySQL compares the names of columns, indexes and constraints: case-insensitively
// (see mysqlFoldsCase) and with every accent kept. Two names with one fold cannot meet in one table.
func foldName(s string) string {
	var b strings.Builder
	for _, r := range s {
		if r < 0x80 || foldsCase(r) {
			r = unicode.ToLower(r)
		}
		b.WriteRune(r)
	}
	return b.String()
}

// MySQLNameFold is foldName for the verifier of the export: a name as MySQL 8.4 compares the names of columns,
// indexes and checks.
func MySQLNameFold(s string) string { return foldName(s) }

func foldsCase(r rune) bool {
	i := sort.Search(len(mysqlFoldsCase), func(i int) bool { return mysqlFoldsCase[i] >= r })
	return i < len(mysqlFoldsCase) && mysqlFoldsCase[i] == r
}

var keyExpansions = strings.NewReplacer("ß", "ss", "æ", "ae", "œ", "oe")

// KeyFold is a text as MySQL's default collation of a utf8mb4 column (utf8mb4_0900_ai_ci) compares it, as far as
// the export can tell without the collation's tables: without case, without accents (the combining marks
// of the decomposed form dropped) and with ß, æ and œ as the letters they stand for. It finds the collisions a
// person meets (`Smith` and `SMITH`, `José` and `Jose`); it does not know the collation's other equalities
// (ignorable characters, compatibility forms, Han variants), so a key it passes can still collide.
func (mysqlDialect) KeyFold(s string) string {
	var b strings.Builder
	for _, r := range norm.NFD.String(s) {
		if unicode.Is(unicode.Mn, r) {
			continue
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return keyExpansions.Replace(b.String())
}
