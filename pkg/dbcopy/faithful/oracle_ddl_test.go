func TestOracleCounterSQL(t *testing.T) {
	p := planOracle(t,
		`CREATE TABLE full_t (id INTEGER PRIMARY KEY AUTOINCREMENT, v TEXT)`, `INSERT INTO full_t (v) VALUES ('a'), ('b'), ('c')`, `DELETE FROM full_t WHERE id > 1`,
		`CREATE TABLE empty_t (id INTEGER PRIMARY KEY AUTOINCREMENT, v TEXT)`,
		`CREATE TABLE plain_t (id INTEGER PRIMARY KEY, v TEXT)`, `INSERT INTO plain_t VALUES (7, 'a'), (3, 'b')`,
		`CREATE TABLE neg_t (id INTEGER PRIMARY KEY, v TEXT)`, `INSERT INTO neg_t VALUES (-5, 'a'), (-3, 'b')`,
		`CREATE TABLE "q'uote" (id INTEGER PRIMARY KEY AUTOINCREMENT, v TEXT)`, `INSERT INTO "q'uote" (v) VALUES ('a')`)
	d := oracleDialect{}
	got := func(table string, next int64) string {
		tb := p.Table(table)
		return d.CounterSQL(tb, tb.Col("id"), next)
	}
	if s := got("full_t", 4); s != `ALTER TABLE "full_t" MODIFY ("id" GENERATED BY DEFAULT AS IDENTITY (START WITH 4));` {
		t.Errorf("%s", s)
	}
	// No counter in SQLite: one after the highest id, and 1 for a table with no row or with ids below 1.
	for table, want := range map[string]int64{"plain_t": 8, "empty_t": 1, "neg_t": 1} {
		if s := got(table, 0); !strings.Contains(s, "(START WITH "+strconv.FormatInt(want, 10)+"))") {
			t.Errorf("%s: %s, want START WITH %d", table, s, want)
		}
	}
	if s := got("q'uote", 2); !strings.Contains(s, `ALTER TABLE "q'uote" MODIFY ("id"`) {
		t.Errorf("%s", s)
	}
	// The script writes the counter of every identity column, and the identity clause is in the table.
	script, _ := exportOracle(t, sqliteWith(t, `CREATE TABLE plain_t (id INTEGER PRIMARY KEY, v TEXT)`, `INSERT INTO plain_t VALUES (7, 'a')`, `CREATE TABLE no_id (a TEXT)`))
	for _, want := range []string{`"id" NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY`, `ALTER TABLE "plain_t" MODIFY ("id" GENERATED BY DEFAULT AS IDENTITY (START WITH 8));`} {
		if !strings.Contains(script, want) {
			t.Errorf("no %q", want)
		}
	}
	if strings.Contains(script, "IDENTITY (START WITH 1)") && !strings.Contains(script, `"plain_t" MODIFY`) {
		t.Error("the counter")
	}
	if oracleIdentity(planOracle(t, `CREATE TABLE no_id (a TEXT)`).Tables[0]) != nil {
		t.Error("no identity")
	}
}

func TestOracleStatements(t *testing.T) {
	e := sqliteWith(t,
		`CREATE TABLE a (id INTEGER PRIMARY KEY AUTOINCREMENT, v TEXT NOT NULL, n NUMERIC(5,2) DEFAULT 1.5 NOT NULL CHECK (n > 0), t TEXT DEFAULT 'x', UNIQUE (v), CONSTRAINT "uq_n" UNIQUE (n))`, `INSERT INTO a (v, n) VALUES ('x', 1), ('y', 2)`,
		`CREATE TABLE b (id INTEGER PRIMARY KEY, a_id INTEGER REFERENCES a(id) ON DELETE CASCADE, a2 INTEGER REFERENCES a(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED, a3 INTEGER, CONSTRAINT "b_fk" FOREIGN KEY (a3) REFERENCES a(id) DEFERRABLE INITIALLY IMMEDIATE)`,
		`CREATE INDEX b_a ON b (a_id DESC, a2)`, `CREATE UNIQUE INDEX b_a2 ON b (a2, a3)`, `INSERT INTO b VALUES (1, 1, 1, 1), (2, 2, NULL, NULL), (3, NULL, NULL, NULL)`,
		`CREATE TABLE empty_t (id INTEGER)`)
	script, _ := exportOracle(t, e)
	for _, want := range []string{
		"CREATE TABLE \"a\" (\n  \"id\" NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,\n  \"v\" VARCHAR2(255 CHAR) NOT NULL,\n  \"n\" NUMBER(5,2) DEFAULT (1.5) NOT NULL,\n  \"t\" VARCHAR2(4000 BYTE) DEFAULT ('x'),\n  PRIMARY KEY (\"id\"),\n  CONSTRAINT \"uq_n\" UNIQUE (\"n\"),\n  UNIQUE (\"v\")\n);",
		"INSERT INTO \"a\" (\"id\", \"v\", \"n\", \"t\") VALUES\n(1,'x',1,'x'),\n(2,'y',2,'x');\nCOMMIT;\n",
		"ALTER TABLE \"a\" MODIFY (\"id\" GENERATED BY DEFAULT AS IDENTITY (START WITH 3));",
		"CREATE INDEX \"b_a\" ON \"b\" (\"a_id\" DESC, \"a2\");",
		"CREATE UNIQUE INDEX \"b_a2\" ON \"b\" (CASE WHEN \"a2\" IS NOT NULL AND \"a3\" IS NOT NULL THEN \"a2\" END, CASE WHEN \"a2\" IS NOT NULL AND \"a3\" IS NOT NULL THEN \"a3\" END);",
		"ALTER TABLE \"a\" ADD CHECK (\"n\" > 0);",
		"ALTER TABLE \"b\" ADD FOREIGN KEY (\"a_id\") REFERENCES \"a\" (\"id\") ON DELETE CASCADE;",
		"ALTER TABLE \"b\" ADD FOREIGN KEY (\"a2\") REFERENCES \"a\" (\"id\") ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED;",
		"ALTER TABLE \"b\" ADD CONSTRAINT \"b_fk\" FOREIGN KEY (\"a3\") REFERENCES \"a\" (\"id\") DEFERRABLE INITIALLY IMMEDIATE;",
		"CREATE TABLE \"empty_t\" (\n  \"id\" NUMBER(19,0)\n);",
	} {
		if !strings.Contains(script, want) {
			t.Errorf("no %q in\n%.2000s", want, script)
		}
	}
	if strings.Contains(script, "ON UPDATE") || strings.Contains(script, "IDENTITY_INSERT") {
		t.Error("Oracle has no ON UPDATE and no IDENTITY_INSERT")
	}
	d := oracleDialect{}
	if d.BeginData(nil) != nil || len(d.EndData(nil)) != 1 || d.InsertHead(p0(t)) == "" {
		t.Error("data framing")
	}
}

func p0(t testing.TB) *ScriptTable {
	return planOracle(t, `CREATE TABLE x (a INTEGER)`).Tables[0]
}

// oracleAllowedLine is what a line of a script may start with: only tokens the generator wrote.
var oracleAllowedLine = regexp.MustCompile(`^(-- |--$|$|SET |WHENEVER |ALTER SESSION |ALTER TABLE |DECLARE$|BEGIN$|END;$|/$|CREATE |INSERT INTO |COMMIT;$|\(|  [A-Za-z"]|    RAISE_APPLICATION_ERROR|'|CHR\(|TO_CHAR\(UNISTR\(|TO_CLOB\(|HEXTORAW\(|TO_BLOB\(|NULL|EMPTY_BLOB\(\)|BINARY_DOUBLE_|-BINARY_DOUBLE_|DATE '|TIMESTAMP '|-?[0-9.]|\);$)`)

// sqlplusCommand is what SQL*Plus reads as a command at the start of a line (leading blanks do not matter).
var sqlplusCommand = regexp.MustCompile(`(?i)^\s*(/|@|@@|!|#|\$|exit|quit|set|rem|remark|prompt|host|start|ed|edit|run|get|save|spool|accept|define|undefine|variable|var|print|whenever|clear|column|col|break|compute|btitle|ttitle|connect|conn|disconnect|describe|desc|execute|exec|help|input|list|pause|password|recover|shutdown|startup|store|timing|xquery|archive|append|change|del|copy|attribute|oradebug|show|sqlplus|storage|--)(\b|$|\s)`)

// oraclePreludeCommands are the only lines SQL*Plus reads as commands that the generator writes: the settings, the WHENEVER
// lines, the "/" that ends a PL/SQL block, and the comments (REM and -- lines).
func oracleCommandLine(l string) bool {
	return strings.HasPrefix(l, "SET ") || strings.HasPrefix(l, "WHENEVER ") || l == "/" || strings.HasPrefix(l, "-- ") || l == "--"
}

// checkOracleLines asserts that every line of a script starts with a token the generator wrote, that the only lines SQL*Plus
// would read as commands are the ones the generator wrote, that no line is longer than the line limit and that no raw
// control character is in it, so no data byte can start a line.
func checkOracleLines(t testing.TB, script string) {
	t.Helper()
	if strings.ContainsAny(script, "\r\x00") {
		t.Fatal("the script holds a raw CR or NUL")
	}
	if strings.HasPrefix(script, "\xef\xbb\xbf") {
		t.Fatal("the script starts with a byte order mark")
	}
	for i, l := range strings.Split(script, "\n") {
		if !oracleAllowedLine.MatchString(l) && !oracleWrapStart(l) {
			t.Fatalf("line %d starts with a token the generator did not write: %.80q", i+1, l)
		}
		if sqlplusCommand.MatchString(l) && !oracleCommandLine(l) {
			t.Fatalf("line %d would be read as a SQL*Plus command: %.80q", i+1, l)
		}
		if len(l) > oracleMaxLine {
			t.Fatalf("line %d is %d characters long (the limit is %d): %.60q", i+1, len(l), oracleMaxLine, l)
		}
		// SQL*Plus joins a line that ends in a hyphen with the next one, outside a "--" comment: no such line is written.
		if strings.HasSuffix(strings.TrimRight(l, " \t"), "-") && !strings.HasPrefix(l, "--") {
			t.Fatalf("line %d ends in a hyphen: %.60q", i+1, l)
		}
		if strings.ContainsAny(l, "\x01\x02\x03\x04\x05\x06\x07\x08\x0b\x0c\x0e\x0f\x1a\x1b\x7f\u0085\u2028\u2029") {
			t.Fatalf("line %d holds a raw control or line-break character: %.80q", i+1, l)
		}
	}
}

