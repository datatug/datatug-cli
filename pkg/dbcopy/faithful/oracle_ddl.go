// oracleIdentity returns the column the table creates as an identity column, or nil.
func oracleIdentity(t *ScriptTable) *ScriptColumn {
	for _, c := range t.Columns {
		if c.AutoInc && c.Choice.Family == "int" {
			return c
		}
	}
	return nil
}

func (d oracleDialect) CreateTable(t *ScriptTable) string {
	var parts []string
	id := oracleIdentity(t)
	for _, c := range t.Columns {
		def := d.QuoteIdent(c.Name) + " " + c.Choice.Type
		if c == id {
			def += " GENERATED BY DEFAULT AS IDENTITY"
		}
		if c.Default != "" {
			def += " DEFAULT " + c.Default
		}
		if c.NotNull && c != id {
			def += " NOT NULL"
		}
		parts = append(parts, def)
	}
	if len(t.PK) > 0 {
		parts = append(parts, "PRIMARY KEY ("+d.quoteList(t.PK)+")")
	}
	for _, u := range t.Uniques {
		s := ""
		if u.Name != "" {
			s += "CONSTRAINT " + d.QuoteIdent(u.Name) + " "
		}
		parts = append(parts, s+"UNIQUE ("+d.quoteList(u.Columns)+")")
	}
	return "CREATE TABLE " + d.QuoteIdent(t.Name) + " (\n  " + strings.Join(parts, ",\n  ") + "\n);"
}

// IndexSQL writes an index. A unique index that carries a Where is the Oracle form of a key over columns that hold NULLs
// (see filterCompositeUniques): every column is written as CASE WHEN <no column is NULL> THEN column END, so a row with a
// NULL in the key has an all-NULL key, which a unique index never holds.
func (d oracleDialect) IndexSQL(t *ScriptTable, ix Index) string {
	cols := make([]string, len(ix.Columns))
	for i, c := range ix.Columns {
		cols[i] = d.QuoteIdent(c.Name)
		if ix.Where != "" {
			cols[i] = "CASE WHEN " + ix.Where + " THEN " + cols[i] + " END"
		}
		if c.Desc {
			cols[i] += " DESC"
		}
	}
	s := "CREATE "
	if ix.Unique {
		s += "UNIQUE "
	}
	return s + "INDEX " + d.QuoteIdent(ix.Name) + " ON " + d.QuoteIdent(t.Name) + " (" + strings.Join(cols, ", ") + ");"
}

func (d oracleDialect) CheckSQL(t *ScriptTable, ck Check) string {
	s := "ALTER TABLE " + d.QuoteIdent(t.Name) + " ADD "
	if ck.Name != "" {
		s += "CONSTRAINT " + d.QuoteIdent(ck.Name) + " "
	}
	return s + "CHECK (" + ck.Expr + ");"
}

func (d oracleDialect) FKSQL(p *ScriptPlan, t *ScriptTable, fk ForeignKey) string {
	s := "ALTER TABLE " + d.QuoteIdent(t.Name) + " ADD "
	if fk.Name != "" {
		s += "CONSTRAINT " + d.QuoteIdent(fk.Name) + " "
	}
	s += "FOREIGN KEY (" + d.quoteList(fk.Columns) + ") REFERENCES " + d.QuoteIdent(fk.RefTable) + " (" + d.quoteList(fk.RefColumns) + ")"
	if fk.OnDelete == "CASCADE" || fk.OnDelete == "SET NULL" {
		s += " ON DELETE " + fk.OnDelete
	}
	if fk.Deferrable {
		s += " DEFERRABLE INITIALLY IMMEDIATE"
		if fk.Deferred {
			s = strings.TrimSuffix(s, "IMMEDIATE") + "DEFERRED"
		}
	}
	return s + ";"
}

// oracleNextIdentity is the number the identity column of a table gives its next row: the counter SQLite keeps when
// it keeps one, else one after the highest id, and at least 1 (an Oracle identity starts at 1).
func oracleNextIdentity(c *ScriptColumn, next int64) int64 {
	if next <= 0 {
		next = 1
		if c.Stats.ints > 0 {
			next = c.Stats.maxInt + 1
		}
	}
	return max(next, 1)
}

// CounterSQL sets the start of the identity counter, so the next row gets the number SQLite would give it. An Oracle
// identity column does not advance when a row is inserted with a value of its own.
func (d oracleDialect) CounterSQL(t *ScriptTable, c *ScriptColumn, next int64) string {
	return "ALTER TABLE " + d.QuoteIdent(t.Name) + " MODIFY (" + d.QuoteIdent(c.Name) + " GENERATED BY DEFAULT AS IDENTITY (START WITH " + strconv.FormatInt(oracleNextIdentity(c, next), 10) + "));"
}

func (d oracleDialect) InsertHead(t *ScriptTable) string {
	names := make([]string, len(t.Columns))
	for i, c := range t.Columns {
		names[i] = c.Name
	}
	return "INSERT INTO " + d.QuoteIdent(t.Name) + " (" + d.quoteList(names) + ") VALUES"
}

// BatchLimits are the most rows of one INSERT ... VALUES and its size. Oracle takes 65,535 rows (ORA-63805 above), but
// parsing grows faster than the number of rows (1,000 rows: 0.4 s, 5,000: 11 s, 20,000: 220 s, measured), and 100 rows
// loads fastest.
func (oracleDialect) BatchLimits() (int, int) { return 100, 128 << 10 }

func (oracleDialect) BeginData(t *ScriptTable) []string { return nil }

func (oracleDialect) EndData(t *ScriptTable) []string { return []string{"COMMIT;"} }

// oracleComment makes text safe for a "-- " comment line: no control character survives, and "&" (a substitution
// variable for a client that runs with DEFINE ON, in a comment too) is followed by a space.
func oracleComment(s string) string {
	return strings.ReplaceAll(commentText(s), "&", "& ")
}

// oracleNoticeLine is the Oracle rule for a line of the licence notice: the header comes before SET DEFINE OFF, so an
// "&" (a substitution variable for a client that runs with DEFINE ON) is followed by a space, as in the other lines.
// A line that ends in "-" is a continuation line in some SQL*Plus commands; in a "--" comment it was measured to join
// nothing (SET and WHENEVER on the next line still ran, on 23.26.3), and the journey checks that on every run.
func oracleNoticeLine(s string) string { return strings.ReplaceAll(s, "&", "& ") }

func (d oracleDialect) Header(p *ScriptPlan, h Header) []string {
	var l []string
	add := func(format string, args ...any) {
		l = append(l, strings.TrimRight("-- "+oracleComment(fmt.Sprintf(format, args...)), " "))
	}
	raw := func(s string) { l = append(l, strings.TrimRight("-- "+s, " ")) }
	name := h.Name
	if name == "" {
		name = "database"
	}
	if h.Edition != "" {
		add("%s", h.Edition)
	}
	add("Dataset: %s", name)
	add("Generated by datatug %s (datatug db copy --to sqlscript:///<file>.sql?dialect=oracle) from a SQLite file with SHA-256 %s", h.Version, h.SourceSHA256)
	if h.License != "" {
		add("Licence: %s", h.License)
	}
	if h.Attribution != "" {
		add("Attribution: %s", h.Attribution)
	}
	if h.Notice != "" {
		raw("")
		l = append(l, NoticeLines("-- ", h.Notice, oracleNoticeLine)...)
	}
	raw("")
	raw("Requires Oracle Database 23ai or later (multi-row INSERT ... VALUES; COMPATIBLE 23 or later). Verified on Oracle AI Database 26ai Free 23.26.3 with SQL*Plus 23.26.3.")
	raw("Load it into an EMPTY schema that may create tables and sequences (identity columns) and has a quota, with SQL*Plus, from the file:")
	raw("  NLS_LANG=.AL32UTF8 sqlplus -L -S <user>/<password>@<service> @<file>.sql")
	raw("The file is UTF-8 without a byte order mark. The database character set must be AL32UTF8 and the client NLS_LANG must say UTF-8: the first statement checks both")
	raw("and stops the load when either differs (a client in another character set would store the text of this file damaged).")
	raw("No data in this file can start a line, so a line is never a SQL*Plus command or a '/'; no line is longer than " + strconv.Itoa(oracleMaxLine) + " characters (SQL*Plus refuses 2,499 in older versions).")
	raw("The script sets DEFINE OFF (a & in a value is no substitution variable) and stops at the first error (WHENEVER SQLERROR EXIT FAILURE ROLLBACK).")
	raw("Oracle commits every DDL statement: the script is NOT one transaction, and a failed load leaves the tables it had created (drop them, and the marker, before loading again).")
	raw("The first statement creates the table " + MySQLMarkerTable + " and fails when it exists (a second load stops there); the last one counts every table and writes the")
	raw("marker row in one PL/SQL block that raises first when a count is wrong: a row there means the load completed, whatever the client did after an error.")
	raw("DROP TABLE " + d.QuoteIdent(MySQLMarkerTable) + " removes the marker once you no longer need it.")
	raw("The empty text is NULL in Oracle: a column that holds an empty text is created without NOT NULL and holds NULL there. Text comparison is binary by default (NLS_COMP=BINARY).")
	raw("A unique key over several columns treats NULLs as equal in Oracle, unlike SQLite: such a key is written as a unique function-based index.")
	tables := make([]string, len(p.Tables))
	for i, t := range p.Tables {
		tables[i] = t.Name
	}
	add("Tables (%d): %s", len(tables), strings.Join(tables, ", "))
	if len(p.Warnings) > 0 {
		raw("")
		add("%d thing(s) are not carried exactly:", len(p.Warnings))
		for _, w := range p.Warnings {
			add("  [%s] %s: %s", w.Kind, w.Object, w.Message)
		}
	}
	return l
}

// oraclePlsql is a PL/SQL block: its lines start with a word the generator wrote, and the block ends with a line of
// its own that holds a "/".
func oraclePlsql(lines ...string) []string {
	return append(lines, "/")
}

func (d oracleDialect) Prelude(p *ScriptPlan, h Header) []string {
	q := d.QuoteIdent(MySQLMarkerTable)
	out := []string{
		"SET DEFINE OFF",
		"SET ESCAPE OFF",
		"SET CMDSEP OFF",
		"SET SQLTERMINATOR ';'",
		"SET SQLPREFIX #",
		"SET ECHO OFF",
		"SET FEEDBACK OFF",
		"SET VERIFY OFF",
		"WHENEVER SQLERROR EXIT FAILURE ROLLBACK",
		"WHENEVER OSERROR EXIT FAILURE ROLLBACK",
		"ALTER SESSION SET NLS_COMP = BINARY NLS_SORT = BINARY;",
	}
	out = append(out, oraclePlsql(
		"DECLARE",
		"  ver VARCHAR2(100);",
		"  compat VARCHAR2(100);",
		"  cs VARCHAR2(100);",
		"BEGIN",
		"  IF DBMS_DB_VERSION.VERSION < 23 THEN",
		"    RAISE_APPLICATION_ERROR(-20001, 'this script needs Oracle Database 23ai or later (multi-row INSERT ... VALUES)');",
		"  END IF;",
		"  DBMS_UTILITY.DB_VERSION(ver, compat);",
		"  IF TO_NUMBER(REGEXP_SUBSTR(compat, '^[0-9]+')) < 23 THEN",
		"    RAISE_APPLICATION_ERROR(-20001, 'COMPATIBLE is ' || compat || ': this script needs COMPATIBLE 23 or later');",
		"  END IF;",
		"  SELECT value INTO cs FROM nls_database_parameters WHERE parameter = 'NLS_CHARACTERSET';",
		"  IF cs <> 'AL32UTF8' THEN",
		"    RAISE_APPLICATION_ERROR(-20002, 'the database character set is ' || cs || ', not AL32UTF8: the text of this script cannot be stored without loss');",
		"  END IF;",
		"  IF 'é€😀' <> TO_CHAR(UNISTR('\\00E9\\20AC\\D83D\\DE00')) THEN",
		"    RAISE_APPLICATION_ERROR(-20003, 'the client did not send this script as UTF-8: set NLS_LANG=.AL32UTF8 and load it again');",
		"  END IF;",
		"END;",
	)...)
	return append(out, "CREATE TABLE "+q+` ("dataset" VARCHAR2(4000 BYTE), "edition" VARCHAR2(4000 BYTE), "source_sha256" VARCHAR2(64 CHAR) NOT NULL, "datatug_version" VARCHAR2(4000 BYTE), "tables_count" NUMBER(10,0) NOT NULL, "rows_count" NUMBER(19,0) NOT NULL);`)
}

func (d oracleDialect) Epilogue(p *ScriptPlan, h Header) []string {
	var rows int64
	block := []string{"DECLARE", "  n NUMBER;", "BEGIN"}
	for _, t := range p.Tables {
		rows += t.Rows
		block = append(block,
			"  SELECT COUNT(*) INTO n FROM "+d.QuoteIdent(t.Name)+";",
			fmt.Sprintf("  IF n <> %d THEN RAISE_APPLICATION_ERROR(-20000, %s); END IF;", t.Rows,
				oracleTextExpr("the load is incomplete: table "+t.Name+" does not hold "+strconv.FormatInt(t.Rows, 10)+" rows", false)))
	}
	block = append(block,
		fmt.Sprintf("  INSERT INTO %s VALUES\n%s;", d.QuoteIdent(MySQLMarkerTable),
			joinRow([]string{oracleOptText(h.Name), oracleOptText(h.Edition), oracleOptText(h.SourceSHA256), oracleOptText(h.Version), strconv.Itoa(len(p.Tables)), strconv.FormatInt(rows, 10)}, oracleMaxLine)),
		"  COMMIT;",
		"END;")
	out := []string{"COMMIT;"}
	out = append(out, oraclePlsql(block...)...)
	return append(out, "-- end of script")
}

// oracleOptText is a text of the marker row: NULL when it is empty (Oracle has no empty text).
func oracleOptText(s string) string {
	if s == "" {
		return "NULL"
	}
	return oracleTextExpr(s, false)
}

// ValidateHeader refuses a dataset name or edition the script cannot carry: invalid UTF-8 cannot be written as text,
// a NUL has no place in a header comment, and the marker columns hold 4,000 bytes.
func (oracleDialect) ValidateHeader(h Header) error {
	for _, f := range []struct{ what, value string }{{"name", h.Name}, {"edition", h.Edition}} {
		switch {
		case !utf8.ValidString(f.value):
			return fmt.Errorf("the %s is not valid UTF-8, which Oracle text cannot hold", f.what)
		case strings.IndexByte(f.value, 0) >= 0:
			return fmt.Errorf("the %s holds a NUL character, which the script header cannot hold", f.what)
		case len(f.value) > oracleMaxVarchar:
			return fmt.Errorf("the %s is %d bytes and the marker column takes at most %d", f.what, len(f.value), oracleMaxVarchar)
		}
	}
	return nil
}
