// pgFixture creates, on a PostgreSQL database, tables that use the types and constraints a copy to
// SQLite has to translate or to report.
func pgFixture(t testing.TB, pg Endpoint) {
	execAll(t, pg.DB,
		`CREATE TABLE dept (
			id serial PRIMARY KEY,
			name varchar(30) NOT NULL UNIQUE,
			code char(3) DEFAULT 'ABC',
			budget numeric(12,2) DEFAULT 0,
			active boolean DEFAULT true,
			opened date,
			at timestamp,
			atz timestamptz,
			t time,
			tiny smallint,
			mid integer,
			f4 real,
			f8 double precision,
			data bytea,
			doc jsonb,
			uid uuid,
			tags text[],
			note text DEFAULT 'x',
			made text DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
			stamp timestamptz DEFAULT now(),
			CONSTRAINT dept_budget_chk CHECK (budget >= 0),
			CONSTRAINT dept_code_chk CHECK (code ~ '^[A-Z]{3}$'),
			CONSTRAINT dept_note_chk CHECK (note = ANY (ARRAY['x', 'y']))
		)`,
		`COMMENT ON COLUMN dept.note IS 'a comment'`,
		`CREATE TABLE emp (
			id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
			dept_id integer REFERENCES dept ON DELETE CASCADE ON UPDATE RESTRICT DEFERRABLE INITIALLY DEFERRED,
			boss bigint REFERENCES emp(id) ON DELETE SET NULL,
			name text NOT NULL COLLATE "C",
			double_id integer GENERATED ALWAYS AS (dept_id * 2) STORED
		)`,
		`CREATE TABLE link (a integer, b integer, PRIMARY KEY (a, b), FOREIGN KEY (a) REFERENCES dept(id))`,
		`CREATE TABLE noident (id integer GENERATED BY DEFAULT AS IDENTITY, k text, PRIMARY KEY (id, k))`,
		`CREATE INDEX emp_dept ON emp (dept_id DESC)`,
		`CREATE UNIQUE INDEX emp_boss ON emp (boss) WHERE boss IS NOT NULL`,
		`CREATE INDEX emp_lower ON emp (lower(name))`,
		`CREATE INDEX emp_hash ON emp USING hash (name)`,
		`CREATE INDEX emp_incl ON emp (dept_id) INCLUDE (name)`,
		`CREATE INDEX emp_partial_bad ON emp (dept_id) WHERE name ~~ 'a%'`,
		`CREATE VIEW emp_names AS SELECT name FROM emp`,
		`CREATE MATERIALIZED VIEW emp_m AS SELECT name FROM emp`,
		`CREATE FUNCTION noop() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$`,
		`CREATE TRIGGER emp_t BEFORE INSERT ON emp FOR EACH ROW EXECUTE FUNCTION noop()`,
		`INSERT INTO dept (name, budget, opened, at, atz, t, tiny, mid, f4, f8, data, doc, uid, tags)
		 VALUES ('eng', 12.50, '1968-12-08', '2020-01-02 03:04:05.25', '2020-01-02 03:04:05+00', '03:04:05', 7, 70000, 1.1, 2.5, '\x00ff', '{"a": 1}', '123e4567-e89b-12d3-a456-426614174000', '{a,b}'),
		        ('ops', 0, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL)`,
		`INSERT INTO emp (dept_id, boss, name) VALUES (1, NULL, 'ann'), (1, 1, 'bob'), (2, NULL, 'cy')`,
		`INSERT INTO link VALUES (1, 1), (1, 2)`,
		`INSERT INTO noident (k) VALUES ('a'), ('b')`,
	)
}

func TestPostgresOriginJourney(t *testing.T) {
	ctx := context.Background()
	pg := newPGDatabase(t)
	pgFixture(t, pg)

	mid := newSQLite(t)
	rep, err := Copy(ctx, pg, mid, Options{})
	if err != nil {
		t.Fatal(err)
	}
	for _, w := range []struct{ kind, object string }{
		{WarnViewNotCarried, "emp_names"}, {WarnViewNotCarried, "emp_m"}, {WarnTriggerNotCarried, "emp_t"},
		{WarnTypeApproximated, "dept.tags"}, {WarnCommentNotCarried, "dept.note"}, {WarnCheckNotCarried, "dept_code_chk"},
		{WarnIndexNotCarried, "emp_lower"}, {WarnIndexNotCarried, "emp_hash"}, {WarnIndexNotCarried, "emp_incl"},
		{WarnIndexNotCarried, "emp_partial_bad"}, {WarnGeneratedColumn, "emp.double_id"}, {WarnCollationNotCarried, "emp.name"},
		{WarnIdentityNotCarried, "noident.id"},
	} {
		if !hasWarning(rep, w.kind, w.object) {
			t.Errorf("no %s warning for %s in %v", w.kind, w.object, rep.Warnings)
		}
	}
	// The SQLite side.
	decl := func(table, col string) string {
		var s string
		if err := mid.DB.QueryRow(`SELECT type FROM pragma_table_info(?) WHERE name = ?`, table, col).Scan(&s); err != nil {
			t.Fatal(err)
		}
		return s
	}
	for col, want := range map[string]string{
		"id": "INTEGER", "name": "VARCHAR(30)", "code": "CHAR(3)", "budget": "DECIMAL_TEXT(12,2)", "active": "BOOLEAN", "opened": "DATE",
		"at": "TIMESTAMP", "atz": "TIMESTAMPTZ", "t": "TIME", "tiny": "INT2", "mid": "INT4", "f4": "FLOAT4", "f8": "FLOAT8",
		"data": "BLOB", "doc": "JSONB_TEXT", "uid": "UUID_TEXT", "tags": "TEXT", "note": "TEXT",
	} {
		if got := decl("dept", col); got != want {
			t.Errorf("dept.%s declared %s, want %s", col, got, want)
		}
	}
	var sqlText string
	_ = mid.DB.QueryRow(`SELECT sql FROM sqlite_master WHERE name = 'dept'`).Scan(&sqlText)
	if !strings.Contains(sqlText, "AUTOINCREMENT") || !strings.Contains(sqlText, "CONSTRAINT") {
		t.Errorf("dept: %s", sqlText)
	}
	var seq int
	_ = mid.DB.QueryRow(`SELECT seq FROM sqlite_sequence WHERE name = 'dept'`).Scan(&seq)
	if seq != 2 {
		t.Errorf("counter %d", seq)
	}
	var v string
	_ = mid.DB.QueryRow(`SELECT budget FROM dept WHERE id = 1`).Scan(&v)
	if v != "12.50" {
		t.Errorf("exact decimal %q", v)
	}
	_ = mid.DB.QueryRow(`SELECT +at FROM dept WHERE id = 1`).Scan(&v)
	if v != "2020-01-02 03:04:05.25" {
		t.Errorf("timestamp %q", v)
	}
	_ = mid.DB.QueryRow(`SELECT quote(f4) FROM dept WHERE id = 1`).Scan(&v)
	if v != "1.1" {
		t.Errorf("real %q", v)
	}
	var fks int
	_ = mid.DB.QueryRow(`SELECT count(*) FROM pragma_foreign_key_list('emp') WHERE on_delete = 'CASCADE' AND on_update = 'RESTRICT'`).Scan(&fks)
	if fks != 1 {
		t.Errorf("foreign key actions: %d", fks)
	}

	// And back to PostgreSQL: the same database, except what the reports said.
	dst := newPGDatabase(t)
	rep2, err := Copy(ctx, mid, dst, Options{})
	if err != nil {
		t.Fatal(err)
	}
	_ = rep2
	diffs, err := Verify(ctx, pg, dst)
	if err != nil {
		t.Fatal(err)
	}
	allowed := func(d Diff) bool {
		switch {
		case d.Object == "dept.id" && d.Aspect == "declared type", // serial -> identity (bigint)
			d.Object == "emp.id" && d.Aspect == "declared type",
			d.Object == "noident.id" && d.Aspect == "declared type",
			d.Object == "emp.dept_id" && d.Aspect == "declared type",
			d.Object == "dept.mid" && d.Aspect == "declared type",
			d.Object == "dept.tiny" && d.Aspect == "declared type",
			d.Object == "link.a" && d.Aspect == "declared type",
			d.Object == "link.b" && d.Aspect == "declared type",
			d.Object == "emp.double_id" && d.Aspect == "declared type",
			d.Object == "dept.tags" && d.Aspect == "declared type", // an array is carried as text
			d.Object == "emp.double_id" && d.Aspect == "data digest",
			d.Object == "dept.code" && (d.Aspect == "declared type" || d.Aspect == "default"), // char(n) -> varchar(n): no blank padding in SQLite
			d.Object == "dept" && d.Aspect == "checks",                                        // the regular expression check is not carried (check-not-carried)
			d.Object == "emp" && d.Aspect == "indexes",                                        // the ~~ partial index is not carried (index-not-carried)
			d.Object == "noident.id" && d.Aspect == "identity":                                // identity of a composite key (identity-not-carried)
			return true
		}
		return false
	}
	for _, d := range diffs {
		if !allowed(d) {
			t.Errorf("diff: %s", d)
		}
	}
}
